import { readFileSync, existsSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { parseFinancesWorkbook, periodFromSheetName } from './finances-workbook';

const FIXTURE = new URL('../../test/fixtures/finances-fictif.xlsx', import.meta.url);

describe('periodFromSheetName', () => {
  it.each([
    ['Novembre2025', '2025-11'],
    ['Fevrier2026', '2026-02'],
    ['Février2026', '2026-02'],
    ['Decembre2025', '2025-12'],
    ['Décembre 2025', '2025-12'],
    ['août_2026', '2026-08'],
  ])('%s → %s', (name, period) => {
    expect(periodFromSheetName(name)).toBe(period);
  });

  it.each(['Feuil1', 'Synthèse', 'Mois2026', 'Janvier26'])('ignores %s', (name) => {
    expect(periodFromSheetName(name)).toBeNull();
  });
});

// Fictional workbook generated by scripts/generate-workbook-fixture.py (same structure as Finances.xlsm).
describe('reference import of the fictional workbook', () => {
  const bytes = new Uint8Array(readFileSync(FIXTURE));
  const result = parseFinancesWorkbook(bytes, {
    fileName: 'finances.xlsx',
    fileHash: '0'.repeat(64),
  });

  it('imports every operation and lists the blank line', () => {
    expect(result.rows).toHaveLength(364);
    expect(result.rejected).toHaveLength(1);
    expect(result.rejected[0]).toMatchObject({
      source: { sheet: 'Avril2026', row: 43 },
      reason: 'noAmount',
    });
  });

  it('recomputes every monthly balance equal to F2, to the cent', () => {
    expect(result.controls).toHaveLength(7);
    for (const control of result.controls ?? []) {
      expect(control.differenceMinor, control.sheet).toBe(0);
    }
    expect(result.controls?.map((c) => c.computedClosingMinor)).toEqual([
      79368, 134261, 157630, 185781, 176975, 186104, 205132,
    ]);
  });

  it('takes the opening balance from G2 of the first sheet', () => {
    expect(result.openingBalanceMinor).toBe(42000);
  });

  it('reports missing months and the hand-typed carry-over of October 2026', () => {
    expect(result.missingPeriods).toEqual(['2026-05', '2026-06', '2026-07', '2026-08', '2026-09']);
    const carry = result.warnings.find((w) => w.code === 'carryTyped');
    expect(carry?.params).toMatchObject({
      sheet: 'Octobre2026',
      previousSheet: 'Avril2026',
      missing: 5,
    });
  });

  it('keeps formulas as amount expressions and undated charges', () => {
    const formula = result.rows.find((r) => r.amountExpression === '-(250-80-25)');
    expect(formula).toMatchObject({ amountMinor: -14500, date: null, period: '2026-10' });
    expect(result.rows.filter((r) => r.date === null)).toHaveLength(11);
  });

  it('maps "Revenu" to income and other types to expense categories', () => {
    expect(result.rows.filter((r) => r.kind === 'income')).toHaveLength(25);
    expect(new Set(result.rows.map((r) => r.categoryName))).toEqual(
      new Set(['Logement', 'Transport', 'Alimentation', 'Loisirs', 'Revenu']),
    );
  });

  it('flags the date typed with a wrong year and tolerates header variants', () => {
    const far = result.warnings.filter((w) => w.code === 'dateFarFromPeriod');
    expect(far).toHaveLength(1);
    expect(far[0]?.params).toMatchObject({ date: '2025-01-06', period: '2026-01' });
    // "Type de Depense" / "Libelle" headers (Mars2026 onwards) are equivalent after normalisation
    expect(result.controls?.find((c) => c.sheet === 'Mars2026')?.rowCount).toBe(78);
    expect(result.warnings.some((w) => w.code === 'headerVariant')).toBe(false);
  });

  it('detects the "prix café" tracker cell', () => {
    expect(result.trackers?.[0]).toMatchObject({ term: 'café', cell: 'O16' });
  });
});

// Optional: run against the real, private workbook (never committed).
const PRIVATE = process.env.FINANCES_XLSM;
describe.runIf(PRIVATE && existsSync(PRIVATE))('private workbook', () => {
  it('matches every F2 to the cent', () => {
    const bytes = new Uint8Array(readFileSync(PRIVATE!));
    const result = parseFinancesWorkbook(bytes, {
      fileName: 'Finances.xlsm',
      fileHash: '0'.repeat(64),
    });
    expect(result.source).toBe('xlsm');
    expect(result.rows).toHaveLength(364);
    expect(result.controls?.every((c) => c.differenceMinor === 0)).toBe(true);
  });
});
