/**
 * Zod schemas: single source of truth for every persisted entity.
 * Shared by the UI forms, the data layer, import and export.
 * TypeScript types are derived from these schemas (see ./types.ts).
 */
import { z } from 'zod';
import { isCivilDate, isPeriod } from '../common/civil-date';
import { LABEL_MAX_LENGTH, NOTE_MAX_LENGTH } from '../common/text';
import { EXPORT_FORMAT } from './constants';

// Strict CSP (no 'unsafe-eval'): never probe or use `new Function` for JIT parsing.
z.config({ jitless: true });

export { SCHEMA_VERSION, EXPORT_FORMAT } from './constants';

export const uuidSchema = z
  .string()
  .regex(/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/, 'uuid');
export const civilDateSchema = z
  .string()
  .regex(/^\d{4}-\d{2}-\d{2}$/)
  .refine(isCivilDate, 'date');
export const periodSchema = z
  .string()
  .regex(/^\d{4}-(0[1-9]|1[0-2])$/)
  .refine(isPeriod, 'period');
export const timestampSchema = z.iso.datetime({ offset: false });
export const currencySchema = z.string().regex(/^[A-Z]{3}$/);
export const minorSchema = z.number().int().refine(Number.isSafeInteger, 'safeInteger');
export const colorSchema = z.string().regex(/^#[0-9a-f]{6}$/i);

const timestamps = {
  createdAt: timestampSchema,
  updatedAt: timestampSchema,
};

// ---------------------------------------------------------------------------
// Operation

export const operationKindSchema = z.enum(['expense', 'income', 'transfer']);
export const operationStatusSchema = z.enum(['cleared', 'planned']);

export const operationSchema = z
  .object({
    id: uuidSchema,
    accountId: uuidSchema,
    date: civilDateSchema.nullable(),
    period: periodSchema,
    amountMinor: minorSchema.refine((v) => v !== 0, 'nonZero'),
    currency: currencySchema,
    kind: operationKindSchema,
    categoryId: uuidSchema.nullable(),
    label: z.string().max(LABEL_MAX_LENGTH),
    amountExpression: z.string().max(200).nullable(),
    note: z.string().max(NOTE_MAX_LENGTH),
    tagIds: z.array(uuidSchema).max(50),
    status: operationStatusSchema,
    recurrenceId: uuidSchema.nullable(),
    /** Occurrence key (date or period) generated by the recurrence; prevents duplicates. */
    recurrenceKey: z.string().max(10).nullable(),
    transferGroupId: uuidSchema.nullable(),
    importBatchId: uuidSchema.nullable(),
    ...timestamps,
    deletedAt: timestampSchema.nullable(),
  })
  .superRefine((op, ctx) => {
    if (op.kind === 'transfer') {
      if (op.transferGroupId === null) {
        ctx.addIssue({
          code: 'custom',
          path: ['transferGroupId'],
          message: 'transferGroupRequired',
        });
      }
      if (op.categoryId !== null) {
        ctx.addIssue({ code: 'custom', path: ['categoryId'], message: 'transferHasNoCategory' });
      }
    } else if (op.categoryId === null) {
      ctx.addIssue({ code: 'custom', path: ['categoryId'], message: 'categoryRequired' });
    }
    if (op.label !== op.label.trim()) {
      ctx.addIssue({ code: 'custom', path: ['label'], message: 'labelNotTrimmed' });
    }
  });

// ---------------------------------------------------------------------------
// Category

export const categoryKindSchema = z.enum(['expense', 'income']);

export const categorySchema = z.object({
  id: uuidSchema,
  name: z.string().trim().min(1).max(60),
  parentId: uuidSchema.nullable(),
  kind: categoryKindSchema,
  color: colorSchema,
  icon: z.string().min(1).max(40),
  order: z.number().int(),
  archived: z.boolean(),
  ...timestamps,
});

// ---------------------------------------------------------------------------
// Budget

export const budgetSchema = z.object({
  id: uuidSchema,
  period: periodSchema,
  /** null = global envelope of the month */
  categoryId: uuidSchema.nullable(),
  amountMinor: minorSchema.refine((v) => v >= 0, 'nonNegative'),
  rollover: z.boolean(),
  ...timestamps,
});

// ---------------------------------------------------------------------------
// Account

export const accountTypeSchema = z.enum(['checking', 'savings', 'cash', 'prepaid']);

export const accountSchema = z.object({
  id: uuidSchema,
  name: z.string().trim().min(1).max(60),
  type: accountTypeSchema,
  currency: currencySchema,
  openingBalanceMinor: minorSchema,
  openingDate: civilDateSchema.nullable(),
  order: z.number().int(),
  archived: z.boolean(),
  ...timestamps,
});

// ---------------------------------------------------------------------------
// Import batch

export const importSourceSchema = z.enum(['xlsm', 'xlsx', 'csv', 'json', 'ofx', 'qif']);

export const importBatchSchema = z.object({
  id: uuidSchema,
  source: importSourceSchema,
  fileName: z.string().max(255),
  fileHash: z.string().regex(/^[0-9a-f]{64}$/),
  importedAt: timestampSchema,
  count: z.number().int().nonnegative(),
  mode: z.enum(['merge', 'replace']),
  createdCategoryIds: z.array(uuidSchema),
  backupId: z.string().max(64).nullable(),
  undoneAt: timestampSchema.nullable(),
});

// ---------------------------------------------------------------------------
// Settings & meta (singletons)

export const themeSchema = z.enum(['system', 'light', 'dark']);
export const localeSchema = z.enum(['fr-FR', 'en-GB']);
export const dateFormatSchema = z.enum(['locale', 'dd/MM/yyyy', 'yyyy-MM-dd']);

export const settingsSchema = z.object({
  id: z.literal('settings'),
  locale: localeSchema,
  currency: currencySchema,
  dateFormat: dateFormatSchema,
  theme: themeSchema,
  budgetMonthStartDay: z.number().int().min(1).max(28),
  /** Effective budget of a month without its own envelopes = latest previous envelopes. */
  budgetAutoRenew: z.boolean(),
  backupReminderDays: z.number().int().min(0).max(365),
  lastBackupAt: timestampSchema.nullable(),
  defaultAccountId: uuidSchema.nullable(),
  updatedAt: timestampSchema,
});

export const metaSchema = z.object({
  id: z.literal('meta'),
  schemaVersion: z.number().int().positive(),
  appVersion: z.string(),
  createdAt: timestampSchema,
});

// ---------------------------------------------------------------------------
// V1: recurrences, rules, tags

export const recurrenceTemplateSchema = z.object({
  accountId: uuidSchema,
  /** Destination account when kind = transfer */
  toAccountId: uuidSchema.nullable(),
  amountMinor: minorSchema.refine((v) => v !== 0, 'nonZero'),
  currency: currencySchema,
  kind: operationKindSchema,
  categoryId: uuidSchema.nullable(),
  label: z.string().max(LABEL_MAX_LENGTH),
  note: z.string().max(NOTE_MAX_LENGTH),
  tagIds: z.array(uuidSchema),
});

export const recurrenceSchema = z.object({
  id: uuidSchema,
  name: z.string().trim().min(1).max(80),
  template: recurrenceTemplateSchema,
  /** RFC 5545 RRULE subset, e.g. "FREQ=MONTHLY;INTERVAL=1;BYMONTHDAY=5" */
  rule: z.string().min(6).max(200),
  dtstart: civilDateSchema,
  /** Generated operations have no date (monthly fixed charge, like "Aucune"). */
  undated: z.boolean(),
  /** Next occurrence not generated yet; null when the rule is exhausted. */
  nextDate: civilDateSchema.nullable(),
  autoConfirm: z.boolean(),
  active: z.boolean(),
  ...timestamps,
});

export const ruleMatchTypeSchema = z.enum(['contains', 'equals', 'startsWith', 'regex']);

export const ruleSchema = z.object({
  id: uuidSchema,
  name: z.string().trim().min(1).max(80),
  matchType: ruleMatchTypeSchema,
  pattern: z.string().min(1).max(200),
  actions: z.object({
    categoryId: uuidSchema.nullable(),
    label: z.string().max(LABEL_MAX_LENGTH).nullable(),
    addTagIds: z.array(uuidSchema),
  }),
  priority: z.number().int(),
  enabled: z.boolean(),
  ...timestamps,
});

export const tagSchema = z.object({
  id: uuidSchema,
  name: z.string().trim().min(1).max(40),
  color: colorSchema,
  ...timestamps,
});

// ---------------------------------------------------------------------------
// V2: goals

export const goalSchema = z.object({
  id: uuidSchema,
  name: z.string().trim().min(1).max(80),
  targetMinor: minorSchema.refine((v) => v > 0, 'positive'),
  dueDate: civilDateSchema.nullable(),
  accountId: uuidSchema.nullable(),
  archived: z.boolean(),
  ...timestamps,
});

// ---------------------------------------------------------------------------
// Export envelope

export const exportDataSchema = z.object({
  accounts: z.array(accountSchema),
  categories: z.array(categorySchema),
  operations: z.array(operationSchema),
  budgets: z.array(budgetSchema),
  recurrences: z.array(recurrenceSchema),
  rules: z.array(ruleSchema),
  tags: z.array(tagSchema),
  goals: z.array(goalSchema),
  importBatches: z.array(importBatchSchema),
  settings: settingsSchema,
});

export const exportEnvelopeSchema = z.object({
  format: z.literal(EXPORT_FORMAT),
  schemaVersion: z.number().int().positive(),
  appVersion: z.string(),
  exportedAt: timestampSchema,
  checksum: z.string().regex(/^sha256-[0-9a-f]{64}$/),
  data: exportDataSchema,
});

/** Loose envelope used before migration: data is validated after migrating. */
export const exportEnvelopeHeaderSchema = z.object({
  format: z.literal(EXPORT_FORMAT),
  schemaVersion: z.number().int().positive(),
  appVersion: z.string(),
  exportedAt: z.string(),
  checksum: z.string(),
  data: z.record(z.string(), z.unknown()),
});
